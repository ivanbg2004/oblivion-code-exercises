-- Tabla PISO mejorada para propiedades inmobiliarias, enlazada a PERSONA
CREATE TABLE PISO (
    ID_PISO INT PRIMARY KEY AUTO_INCREMENT,
    DIRECCION VARCHAR2(100) NOT NULL,
    CIUDAD VARCHAR2(50) NOT NULL,
    PRECIO DECIMAL(10,2) CHECK (PRECIO > 0),
    METROS_CUADRADOS INT CHECK (METROS_CUADRADOS > 0),
    DNI_DUENO CHAR(9),
    FOREIGN KEY (DNI_DUENO) REFERENCES PERSONA(DNI) ON DELETE CASCADE
);

-- Inserts de ejemplo
INSERT INTO PISO (DIRECCION, CIUDAD, PRECIO, METROS_CUADRADOS, DNI_DUENO) VALUES ('Calle Mayor 1', 'Madrid', 150000.00, 80, '10000000A');
INSERT INTO PISO (DIRECCION, CIUDAD, PRECIO, METROS_CUADRADOS, DNI_DUENO) VALUES ('Avenida Libertad 5', 'Barcelona', 200000.00, 100, '20000000A');

-- Índice para búsquedas por ciudad
CREATE INDEX idx_ciudad ON PISO(CIUDAD);

-- Vista para pisos caros
CREATE VIEW pisos_caros AS
SELECT p.DIRECCION, p.CIUDAD, p.PRECIO, per.NOMBRE AS DUENO
FROM PISO p
JOIN PERSONA per ON p.DNI_DUENO = per.DNI
WHERE p.PRECIO > 180000;

-- Trigger para logging de inserts
CREATE TRIGGER log_piso_insert AFTER INSERT ON PISO
FOR EACH ROW
BEGIN
    INSERT INTO LOG_PISOS (ACCION, ID_PISO, FECHA) VALUES ('INSERT', :NEW.ID_PISO, SYSDATE);
END;

-- Tabla de log (necesaria para el trigger)
CREATE TABLE LOG_PISOS (
    ID_LOG INT PRIMARY KEY AUTO_INCREMENT,
    ACCION VARCHAR2(10),
    ID_PISO INT,
    FECHA DATE
);
